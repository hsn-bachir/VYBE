// Isolated browser acceptance; fixtures never enter production code or a database.
export async function runHomepageRefinementChecks(page, base = 'http://localhost:5173') {
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const checks = []
  const requests = []
  let failNext = false
  let count = 12
  const headers = { 'Access-Control-Allow-Origin': base, 'Access-Control-Allow-Credentials': 'true' }
  const movie = id => ({ tmdb_id: id, title: 'Test film ' + id, overview: 'Isolated acceptance fixture for layout and playback testing.',
    poster_path: id === 44 ? null : '/pB8BM7pdSp6B6Ih7QZ4DrQ3PmJK.jpg', backdrop_path: '/hZkgoQYus5vegHoetLkCJzb17zJ.jpg',
    release_date: '2025-01-02', tmdb_rating: 8.4, tmdb_vote_count: 1200 })
  await page.unroute('**/api/v1/**')
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url())
    if (url.pathname.endsWith('/auth/me')) return route.fulfill({ status: 401, headers, json: { message: 'Unauthenticated.' } })
    requests.push(url)
    if (/\/movies\/\d+$/.test(url.pathname)) return route.fulfill({ headers, json: { data: { ...movie(Number(url.pathname.split('/').at(-1))), original_title: null, runtime: 120, original_language: 'en', genres: [] }, meta: { stale: false } } })
    const p = Number(url.searchParams.get('page') || 1)
    if (url.pathname.endsWith('/popular') && p === 2 && failNext) { failNext = false; return route.fulfill({ status: 503, headers, json: { code: 'UPSTREAM_UNAVAILABLE' } }) }
    const rows = Array.from({ length: count }, (_, i) => movie(42 + (p - 1) * 12 + i))
    if (url.pathname.endsWith('/popular') && p === 2) rows[0] = movie(42)
    return route.fulfill({ headers, json: { data: rows, meta: { page: p, total_pages: 3, total_results: 35 } } })
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install()
  await page.goto(base)
  await page.getByRole('button', { name: 'Load more movies' }).waitFor()
  assert(await page.locator('.brand-hero h1').textContent() === 'Morethan movies.', 'Hero headline failed')
  assert(await page.locator('.spotlight-slide').count() === 5, 'Expected five Spotlight movies')
  assert(requests.filter(u => u.pathname.endsWith('/popular')).length <= 2, 'Spotlight made extra metadata requests')
  checks.push('Reference artwork, hero hierarchy and shared popular response')
  await page.getByRole('searchbox', { name: 'Search movie titles' }).fill('quiet & bright')
  await page.getByRole('searchbox', { name: 'Search movie titles' }).press('Enter')
  await page.waitForURL(u => u.pathname === '/discover' && u.searchParams.get('query') === 'quiet & bright')
  await page.getByRole('heading', { name: 'Results for “quiet & bright”' }).waitFor()
  checks.push('Hero Enter search preserves and encodes the query')
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search movie titles' }).fill('second search')
  await page.getByRole('button', { name: 'Search movies', exact: true }).click()
  await page.waitForURL(u => u.searchParams.get('query') === 'second search')
  checks.push('Hero search action works')
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await page.waitForTimeout(650)
  const before = await page.locator('.nav-indicator').evaluate(el => getComputedStyle(el).transform)
  await page.getByRole('link', { name: 'Discover', exact: true }).click()
  const initial = await page.locator('.nav-indicator').evaluate(el => getComputedStyle(el).transform)
  await page.waitForTimeout(80)
  const middle = await page.locator('.nav-indicator').evaluate(el => getComputedStyle(el).transform)
  await page.waitForTimeout(650)
  const after = await page.locator('.nav-indicator').evaluate(el => getComputedStyle(el).transform)
  assert(before !== after && initial !== after && middle !== before && middle !== after, 'Navigation indicator did not visibly travel')
  checks.push('One measured navigation indicator interpolates between routes')
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  const current = () => page.locator('.spotlight-slide.is-active').getAttribute('aria-label')
  const interval = await page.locator('.spotlight-progress span').evaluate(el => Number.parseFloat(getComputedStyle(el).animationDuration) * 1000)
  await page.mouse.move(1, 1)
  await page.waitForTimeout(200)
  const first = await current()
  await page.clock.fastForward(interval + 100)
  await page.waitForFunction(value => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') !== value, first)
  assert(await current() !== first, 'Spotlight did not rotate at the configured interval')
  checks.push('Automatic rotation at the configured interval')
  await page.locator('.spotlight').hover()
  const hoverSlide = await current()
  await page.clock.fastForward(interval + 1000)
  assert(await current() === hoverSlide, 'Spotlight changed while hovered')
  await page.mouse.move(1, 1)
  await page.getByRole('button', { name: 'Next spotlight movie' }).focus()
  await page.clock.fastForward(interval + 1000)
  assert(await current() === hoverSlide, 'Spotlight changed while focused')
  checks.push('Hover and keyboard focus pause playback')
  await page.getByRole('button', { name: 'Next spotlight movie' }).click()
  await page.waitForFunction(value => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') !== value, hoverSlide)
  assert(await current() !== hoverSlide, 'Manual next failed')
  await page.getByRole('button', { name: 'Previous spotlight movie' }).click()
  await page.waitForFunction(value => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') === value, hoverSlide)
  assert(await current() === hoverSlide, 'Manual previous failed')
  await page.getByRole('button', { name: 'Show Test film 46', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') === '5 of 5')
  assert(await current() === '5 of 5', 'Direct slide selection failed')
  checks.push('Manual previous/next')
  await page.getByRole('button', { name: 'Pause automatic Spotlight' }).click()
  await page.locator('.brand-hero h1').click()
  const pausedSlide = await current()
  await page.clock.fastForward(interval + 1000)
  assert(await current() === pausedSlide, 'Explicit pause failed')
  await page.getByRole('button', { name: 'Resume automatic Spotlight' }).click()
  await page.locator('.brand-hero h1').click()
  await page.clock.fastForward(interval + 100)
  await page.waitForFunction(value => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') !== value, pausedSlide)
  assert(await current() !== pausedSlide, 'Explicit resume failed')
  checks.push('Explicit pause/resume')
  await page.clock.fastForward(interval - 1000)
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  const hiddenSlide = await current()
  await page.clock.fastForward(interval + 1000)
  assert(await current() === hiddenSlide, 'Hidden-tab pause failed')
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')) })
  await page.clock.fastForward(interval - 1000)
  assert(await current() === hiddenSlide, 'Returning to the tab did not receive a full scene interval')
  await page.clock.fastForward(1100)
  await page.waitForFunction(value => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') !== value, hiddenSlide)
  checks.push('Visibility-change pause and full interval on return')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForTimeout(30)
  const reducedSlide = await current()
  await page.clock.fastForward(interval + 1000)
  assert(await current() === reducedSlide, 'Reduced motion still rotated automatically')
  assert(await page.getByRole('button', { name: 'Automatic rotation disabled for reduced motion' }).isDisabled(), 'Reduced motion control not explicit')
  await page.getByRole('button', { name: 'Next spotlight movie' }).click()
  await page.waitForFunction(value => document.querySelector('.spotlight-slide.is-active')?.getAttribute('aria-label') !== value, reducedSlide)
  assert(await current() !== reducedSlide, 'Reduced motion should retain manual controls')
  checks.push('Reduced motion stops autoplay and keeps manual navigation')
  await page.clock.resume()
  const load = page.getByRole('button', { name: 'Load more movies' })
  await load.scrollIntoViewIfNeeded()
  const y = await page.evaluate(() => scrollY)
  failNext = true
  await load.click()
  await page.getByRole('button', { name: 'Try loading more' }).waitFor()
  assert(await page.locator('.movie-card').count() === 12, 'Load error removed existing movies')
  await page.getByRole('button', { name: 'Try loading more' }).click()
  await page.waitForFunction(() => document.querySelectorAll('.movie-card').length === 23)
  assert(Math.abs(await page.evaluate(() => scrollY) - y) < 8, 'Load More moved the viewport')
  checks.push('Load More retry, append, deduplication and stable scroll')
  const savedY = await page.evaluate(() => scrollY)
  const countBeforeReturn = requests.filter(u => u.pathname.endsWith('/popular')).length
  await page.locator('.movie-card').nth(8).click()
  await page.getByRole('link', { name: 'Back to discovery' }).click()
  await page.waitForURL(base + '/')
  await page.waitForFunction(() => document.querySelectorAll('.movie-card').length === 23)
  assert(await page.locator('.movie-card').count() === 23, 'Returning home lost loaded pages')
  assert(await page.evaluate(() => scrollY) > 500, 'Returning home lost browsing position')
  assert(requests.filter(u => u.pathname.endsWith('/popular')).length === countBeforeReturn, 'Returning home refetched popular pages')
  checks.push('Cached feed survives detail navigation')
  await page.getByRole('button', { name: 'Load more movies' }).click()
  await page.waitForFunction(() => document.querySelectorAll('.movie-card').length === 35)
  await page.getByText('You’re all caught up.').waitFor()
  assert(await page.getByRole('button', { name: 'Load more movies' }).count() === 0, 'Load More did not stop')
  checks.push('Final popular page stops loading')
  await page.goto(base + '/discover?query=test')
  await page.getByRole('heading', { name: 'Results for “test”' }).waitFor()
  await page.getByRole('link', { name: 'Next page' }).click()
  await page.waitForURL(u => u.searchParams.get('page') === '2')
  await page.waitForTimeout(100)
  const resultsTop = await page.locator('.search-results').evaluate(el => el.getBoundingClientRect().top)
  const headerBottom = await page.locator('.app-header').evaluate(el => el.getBoundingClientRect().bottom)
  assert(resultsTop >= headerBottom && resultsTop < headerBottom + 80, 'Discover results hidden under header or scrolled to app top')
  await page.goBack()
  await page.waitForURL(u => !u.searchParams.has('page'))
  assert(await page.getByRole('searchbox', { name: 'Search movies', exact: true }).inputValue() === 'test', 'Back lost query')
  checks.push('Discover pagination and history scroll to results below sticky nav')
  for (const width of [360, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: width < 600 ? 844 : 1000 })
    await page.goto(base)
    await page.getByRole('button', { name: 'Load more movies' }).waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Homepage overflow at ' + width)
    const hero = await page.locator('.brand-hero').boundingBox()
    const spotlight = await page.locator('.spotlight').boundingBox()
    assert(spotlight.height < hero.height, 'Spotlight dominates hero at ' + width)
    const aligned = await page.locator('.discovery-nav').evaluate(nav => {
      const line = nav.querySelector('.nav-indicator').getBoundingClientRect()
      const active = nav.querySelector('[aria-current=page]').getBoundingClientRect()
      return Math.abs(line.left - active.left) < 1 && Math.abs(line.width - active.width) < 1
    })
    assert(aligned, 'Navigation indicator misaligned at ' + width)
  }
  checks.push('Responsive homepage at 360/768/1024/1440 and balanced sections')
  count = 1
  await page.goto(base)
  await page.locator('.spotlight-slide.is-active').waitFor()
  assert(await page.getByRole('button', { name: 'Next spotlight movie' }).count() === 0, 'Single-film carousel has needless rotation')
  checks.push('Single-film fallback')
  await page.unroute('**/api/v1/**')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  return { passed: checks.length, checks, savedY }
}
